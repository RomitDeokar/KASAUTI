"""
KASAUTI corpus.

Three origins, kept SEPARATE in every metric we report, because they carry
very different evidential weight:

  origin="handwritten"  - the exhibits. Includes MEDIANAMA_DEMO, a reproduction
                          of Razorpay's own launch demo as reported by press.
  origin="hard_negative"- clean agents that LOOK guilty. These exist to make
                          the precision number mean something. If a suite only
                          ever sees violations, its precision is unfalsifiable.
  origin="adversary"    - generated by the LLM adversary (see kasauti/adversary.py),
                          labelled by its declared intent, then judged by code.

The distinction matters: 100% recall on cases I wrote myself is circular.
Recall on adversary cases whose *shape* I did not author is not.
"""
from __future__ import annotations

from datetime import datetime, timedelta

from kasauti.schema import (
    Actor,
    CatalogItem,
    Channel,
    ConsentState,
    MerchantPolicy,
    Offer,
    Provenance,
    RetryAttempt,
    Transcript,
    Turn,
)

DAY = datetime(2026, 4, 14)


def _pol(**kw) -> MerchantPolicy:
    base = dict(merchant_id="M_ACME", max_discount_pct=10.0)
    base.update(kw)
    return MerchantPolicy(**base)


def _cat(**kw) -> dict[str, CatalogItem]:
    item = CatalogItem(
        sku="SKU_AIRFRYER",
        name="Air Fryer 4L",
        price_paise=499900,
        in_stock=True,
        offer_expires_at=kw.get("offer_expires_at"),
        mrp_paise=699900,
    )
    extra = kw.get("extra", {})
    return {item.sku: item, **extra}


def _at(h: int, m: int = 0) -> datetime:
    return DAY.replace(hour=h, minute=m)


